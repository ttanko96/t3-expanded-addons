static const uint8_t *glyph(unsigned char c) {
    if (c >= 'a' && c <= 'z') c = (unsigned char)(c - 'a' + 'A');
    if (c < 32 || c > 95) c = '?';
    return glyphs[c - 32];
}

int tmst_text_width(const char *text, int scale) {
    int n = 0;
    while (text && text[n]) n++;
    return n * TMST_FONT_CELL_W * scale;
}

void tmst_fill_argb(uint32_t *dst, int w, int h, int x, int y, int rw, int rh, uint32_t argb) {
    for (int yy = y < 0 ? 0 : y; yy < y + rh && yy < h; yy++)
        for (int xx = x < 0 ? 0 : x; xx < x + rw && xx < w; xx++) dst[yy * w + xx] = argb;
}

void tmst_text_argb(uint32_t *dst, int w, int h, int x, int y, const char *text, int scale, uint32_t argb) {
    for (int i = 0; text && text[i]; i++) {
        const uint8_t *g = glyph((unsigned char)text[i]);
        int cx = x + i * TMST_FONT_CELL_W * scale;
        for (int row = 0; row < 7; row++)
            for (int col = 0; col < 5; col++)
                if (g[row] >> (4 - col) & 1)
                    tmst_fill_argb(dst, w, h, cx + col * scale, y + row * scale, scale, scale, argb);
    }
}
